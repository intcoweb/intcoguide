def solve3(A, b):
    n = 3
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[p] = M[p], M[c]
        for r in range(n):
            if r != c and M[r][c] != 0:
                f = M[r][c] / M[c][c]
                for k in range(c, n + 1):
                    M[r][k] -= f * M[c][k]
    return [M[i][n] / M[i][i] for i in range(n)]
def fit(idx):
    A = [[0.0]*3 for _ in range(3)]; b = [0.0]*3
    for r in refs:
        v = [float(r[3]), float(r[4]), 1.0]; t = r[idx]
        for i in range(3):
            for j in range(3):
                A[i][j] += v[i]*v[j]
            b[i] += v[i]*t
    return solve3(A, b)
